def replace_section(text: str, heading: str, content: str) -> str:
    """定向替换一个二级标题正文。"""
    pattern = rf"(^## {re.escape(heading)}\n).*?(?=^## |\Z)"
    return re.sub(pattern, rf"\1\n{content.rstrip()}\n\n", text, flags=re.M | re.S)


