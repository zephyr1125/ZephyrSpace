def dcf(fcfs, w, g):
    pv = sum(f / (1 + w) ** (i + 1) for i, f in enumerate(fcfs))
    return pv + fcfs[-1] * (1 + g) / (w - g) / (1 + w) ** len(fcfs) + nc

